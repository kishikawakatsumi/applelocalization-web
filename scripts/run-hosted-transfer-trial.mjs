// Fixed small AppOS only. Upload sealed/ and report.json, never work/.
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { lstat, mkdir, readFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { parseArgs, promisify } from 'node:util';
import { pathToFileURL } from 'node:url';
import { arch } from 'node:os';
import { fileHash, writeJson } from './collection-checkpoints.mjs';
import { runHostedImageTrial } from './run-hosted-image-trial.mjs';
import { exportTransfer } from './package-transfer.mjs';
import { sealTransfer } from './sealed-package-transfer.mjs';

export async function runHostedTransferTrial({ output, allowDownload = false }) {
  assert.equal(allowDownload, true, 'Requires --allow-download');
  assert.equal(process.platform, 'darwin'); assert.equal(arch(), 'arm64');
  output = resolve(output); await mkdir(output, { mode: 0o700 });
  const work = join(output, 'work'); await mkdir(work, { mode: 0o700 });
  const config = JSON.parse(await readFile(new URL('./hosted-transfer-trial.json', import.meta.url)));
  const run = promisify(execFile), tool = join(work, 'tool'); await mkdir(tool);
  const archive = join(tool, 'age.tar.gz');
  await run('/usr/bin/curl', ['--fail', '--silent', '--show-error', '--location', '--proto', '=https', '--proto-redir', '=https', '--max-time', '240', '--max-filesize', String(20 * 1024 ** 2), '--output', archive, config.tool.url], { timeout: 250000 });
  assert.equal((await lstat(archive)).size, config.tool.archiveBytes);
  assert.equal(await fileHash(archive), config.tool.archiveSha256);
  await run('/usr/bin/tar', ['-xzf', archive, '-C', tool, 'age/age', 'age/age-keygen', 'age/LICENSE']);
  const age = join(tool, 'age/age'), keygen = join(tool, 'age/age-keygen');
  assert.equal(await fileHash(age), config.tool.binarySha256);
  assert.equal(await fileHash(keygen), config.tool.keygenSha256);
  // Synthetic keys generated by tests stay on runner and are never uploaded.
  await run(process.execPath, ['--test', 'tests/sealed-package-transfer.test.mjs'], { env: { ...process.env, TEST_AGE: age, TEST_AGE_KEYGEN: keygen }, timeout: 120000 });
  const trial = await runHostedImageTrial({ output: join(work, 'trial'), allowDownload, profile: 'appos' });
  const exported = await exportTransfer({ collection: join(work, 'trial/job/collection'), output: join(work, 'transfer') });
  const sealed = await sealTransfer({ input: join(work, 'transfer'), output: join(output, 'sealed'), manifestSha256: exported.manifestSha256, recipient: config.recipient, age, ageSha256: config.tool.binarySha256 });
  const report = { formatVersion: 1, status: 'hosted-audited-package-encrypted-not-received', imported: false, published: false,
    senderCommit: process.env.GITHUB_SHA ?? null, runId: process.env.GITHUB_RUN_ID ?? null, runAttempt: process.env.GITHUB_RUN_ATTEMPT ?? null,
    sourceId: exported.sourceId, counts: exported.counts, payloadBytes: exported.payloadBytes, ...sealed,
    trialStatus: trial.status, baselineComparison: trial.baselineComparison, detached: trial.detached,
    limitations: ['Only the fixed small AppOS component was transferred.', 'Public artifacts contain ciphertext and metadata only; the recipient secret key is not on Actions.', 'Sender hash must be obtained from the trusted run, not an untrusted transferred index.', 'Receiver acceptance, original-image re-audit, DB import and publication are separate stages.'] };
  // sealed.status is a transport status, not proof of durable receipt.
  report.status = 'hosted-audited-package-encrypted-not-received';
  await writeJson(join(output, 'report.json'), report);
  console.log(JSON.stringify(report, null, 2));
  return report;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { values } = parseArgs({ options: { output: { type: 'string' }, 'allow-download': { type: 'boolean', default: false } } });
  assert.ok(values.output); await runHostedTransferTrial({ output: values.output, allowDownload: values['allow-download'] });
}
